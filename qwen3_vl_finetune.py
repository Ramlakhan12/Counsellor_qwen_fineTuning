# ─── Step 9: Inference (text-only, VL-safe) ────────────────────────────────
from unsloth import FastLanguageModel
import torch, json

FastLanguageModel.for_inference(model)

SYSTEM = (
    "You are an Intent Extraction assistant.Intent can be multiple. "
    "You MUST respond with ONLY valid JSON. No extra text, no explanation. "
    "Use exactly this schema:\n"
    '{"intent": "<short intent label>", "description": "<one sentence summary>"}'
)

TEST_TRANSCRIPT = (
    transcript
)

# ✅ Seed the assistant turn with `{` to force JSON generation
prompt = (
    f"<|im_start|>system\n{SYSTEM}<|im_end|>\n"
    f"<|im_start|>user\n{TEST_TRANSCRIPT}<|im_end|>\n"
    f"<|im_start|>assistant\n{{"       # ← forces model to continue as JSON
)

text_tokenizer = tokenizer
input_ids      = text_tokenizer.encode(prompt, return_tensors="pt").to("cuda")
attention_mask = torch.ones_like(input_ids)

with torch.no_grad():
    output_ids = model.generate(
        input_ids      = input_ids,
        attention_mask = attention_mask,
        max_new_tokens = 128,
        temperature    = 0.1,
        do_sample      = True,
        pad_token_id   = text_tokenizer.eos_token_id,
    )

raw = text_tokenizer.decode(
    output_ids[0][input_ids.shape[1]:],
    skip_special_tokens=True
)

# --- FIX: Extract clean JSON by finding the first and last curly braces ---
first_brace = raw.find("{")
last_brace  = raw.rfind("}")

if first_brace != -1 and last_brace != -1 and first_brace < last_brace:
    response = raw[first_brace : last_brace + 1]
else:
    response = raw # Fallback if no valid JSON structure is found
# -------------------------------------------------------------------------

print("📝 Raw:", response)
try:
    parsed = json.loads(response)
    print("\n✅ Intent :", parsed.get("intent"))
    print("📄 Desc   :", parsed.get("description"))
except json.JSONDecodeError:
    print("⚠️  Not clean JSON yet — raw output:", response)

# ─── Step 9b: Pretty-print JSON response ───────────────────────────────────
try:
    parsed = json.loads(response)
    print("✅ Valid JSON output:")
    print(json.dumps(parsed, indent=2, ensure_ascii=False))
except json.JSONDecodeError:
    print("⚠️  Response is not pure JSON — raw text:")
    print(response)

