def sharegpt_to_text(example):
    try:
        messages = [
            {
                "role"   : ROLE_MAP.get(msg["from"], msg["from"]),
                "content": [{"type": "text", "text": msg["value"]}],  # ← FIX
            }
            for msg in example["conversations"]
        ]
        text = tokenizer.apply_chat_template(
            messages,
            tokenize              = False,
            add_generation_prompt = False,
        )
        return {"text": text.strip()}
    except Exception as e:
        print(f"⚠️  Skipped — {type(e).__name__}: {e}")
        return {"text": ""}

# ─── Step 5b: Convert ShareGPT → Qwen chat-template text ──────────────────
# Map ShareGPT roles to standard HuggingFace roles
ROLE_MAP = {
    "system" : "system",
    "human"  : "user",
    "gpt"    : "assistant",
    "user"   : "user",
    "assistant": "assistant",
}

def sharegpt_to_text(example):
    """Convert one ShareGPT record → tokenizer chat-template string."""
    try:
        messages = [
            {"role": ROLE_MAP.get(msg["from"], msg["from"]),
             "content": msg["value"]}
            for msg in example["conversations"]
        ]
        text = tokenizer.apply_chat_template(
            messages,
            tokenize             = False,
            add_generation_prompt= False,
        )
        return {"text": text.strip()}
    except Exception as e:
        print(f"⚠️  Skipped — {type(e).__name__}: {e}")
        return {"text": ""}

